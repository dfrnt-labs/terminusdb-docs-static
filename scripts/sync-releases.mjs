#!/usr/bin/env node

/**
 * sync-releases.mjs — Sync TerminusDB GitHub release notes into the docs site.
 *
 * Fetches https://api.github.com/repos/terminusdb/terminusdb/releases
 * (paginated, GITHUB_TOKEN used when set), caches the raw JSON in
 * src/data/releases.json, and generates:
 *
 *   - src/app/docs/releases/page.md                  (index, fully generated)
 *   - src/app/docs/releases/<line>-changelog/page.md (one changelog per minor line, fully generated)
 *   - src/app/docs/releases/<version>/page.md (draft stubs for releases
 *     with new functionality and no feature page yet — created once, never overwritten)
 *
 * Run: npm run sync:releases
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.join(__dirname, '..')
const DATA_FILE = path.join(REPO_ROOT, 'src/data/releases.json')
const RELEASES_DIR = path.join(REPO_ROOT, 'src/app/docs/releases')
const SITE = 'https://terminusdb.com'
const GH_REPO = 'terminusdb/terminusdb'
const API_URL = `https://api.github.com/repos/${GH_REPO}/releases`
const MARKER = '<!-- generated by scripts/sync-releases.mjs, do not edit -->'

// Minor lines we publish, newest first. Everything before 10.0 lands in 1-to-4.
const LINES = [
  { id: '12.0', slug: '12-0-changelog', title: 'TerminusDB 12.0' },
  { id: '11.1', slug: '11-1-changelog', title: 'TerminusDB 11.1' },
  { id: '11.0', slug: '11-0-changelog', title: 'TerminusDB 11.0' },
  { id: '10.1', slug: '10-1-changelog', title: 'TerminusDB 10.1' },
  { id: '10.0', slug: '10-0-changelog', title: 'TerminusDB 10.0' },
  { id: '1-to-4', slug: '1-to-4-changelog', title: 'TerminusDB 1.x – 4.x' },
]

// Release-note sections that announce user-facing functionality.
// A release matching one of these gets a feature page (or a draft stub).
const FEATURE_SECTION =
  /^(new functionality|features?|new|enhancements?|highlights.*)$/i

// ─────────────────────────────────────────────────────────────────────────────
// Fetch
// ─────────────────────────────────────────────────────────────────────────────

async function fetchAllReleases() {
  const headers = {
    Accept: 'application/vnd.github+json',
    'User-Agent': 'terminusdb-docs-static-sync',
    'X-GitHub-Api-Version': '2022-11-28',
  }
  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`
  }

  const all = []
  for (let page = 1; page <= 10; page++) {
    const res = await fetch(`${API_URL}?per_page=100&page=${page}`, { headers })
    if (!res.ok) {
      throw new Error(`GitHub API ${res.status}: ${await res.text()}`)
    }
    const batch = await res.json()
    all.push(...batch)
    if (batch.length < 100) break
  }
  return all
}

// ─────────────────────────────────────────────────────────────────────────────
// Normalization
// ─────────────────────────────────────────────────────────────────────────────

function lineFor(version) {
  const [major, minor] = version.split('.').map(Number)
  if (major >= 10) {
    const id = `${major}.${minor}`
    if (LINES.some((l) => l.id === id)) return id
  }
  return '1-to-4'
}

/**
 * Default directory slug for a release page: version first, no decoration.
 * Authors rename the directory to append the headline capability
 * (e.g. 12-0-8-uuid-v7-faster-json-loading). Renames are safe: pages are
 * identified by their frontmatter release.version, never by directory name.
 */
function slugFor(version) {
  return version.replace(/\./g, '-')
}

function anchorFor(version) {
  return `v${version.replace(/\./g, '-')}`
}

/** Extract PR/issue links from a bullet, tolerating mangled markdown. */
function extractRefLinks(text) {
  const links = new Map()
  for (const m of text.matchAll(
    /\[(?:#|GH-?)?(\d+)\]\((https?:\/\/github\.com\/[^)\s]+)\)/g,
  )) {
    links.set(m[1], m[2])
  }
  for (const m of text.matchAll(
    /https?:\/\/github\.com\/terminusdb\/terminusdb\/(?:pull|issues)[/)]\s*(\d+)/g,
  )) {
    links.set(m[1], `https://github.com/${GH_REPO}/pull/${m[1]}`)
  }
  return [...links.values()]
}

/** Strip "by @user in", normalize PR links to ([#N](url)) at the end. */
function normalizeBullet(line) {
  const indent = line.match(/^(\s*)/)[1]
  let text = line.trim()

  const refs = extractRefLinks(text)

  // Remove "by @user in ..." attribution up to end of line (refs already saved).
  text = text.replace(/\s+by\s+@.*$/i, '')

  // Remove any remaining PR/issue links (they are re-appended normalized below).
  text = text.replace(
    /\[[^\]]*\]\(https?:\/\/github\.com\/terminusdb\/terminusdb\/(?:pull|issues)[^)]*\)/g,
    '',
  )
  text = text.replace(
    /https?:\/\/github\.com\/terminusdb\/terminusdb\/(?:pull|issues)[^\s)]*/g,
    '',
  )

  // Tidy leftovers from link stripping.
  text = text
    .replace(/\(\s*\)/g, '')
    .replace(/\[\s*\]/g, '')
    .replace(/\s+in\s*$/i, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([,.;:])/g, '$1')
    .trim()

  // Normalize list marker to "- ".
  const marker = /^[*-]\s+/.test(text) ? '- ' : ''

  if (refs.length) {
    const refList = refs
      .map((u) => `[#${u.match(/(\d+)\s*$/)[1]}](${u})`)
      .join(', ')
    text = `${text} (${refList})`
  }

  return `${indent}${marker}${text.replace(/^[*-]\s+/, '')}`
}

/** Parse a GitHub release body into preamble + titled sections. */
function parseBody(body) {
  const lines = (body || '').split('\n')
  const preamble = []
  const sections = []
  let cur = null

  for (const raw of lines) {
    const heading = raw.match(/^#{1,4}\s+(.+?)\s*$/)
    // Some releases use "**Title**:" as a pseudo-heading.
    const pseudo = raw.match(/^\*\*(.+?)\*\*:?\s*$/)
    if (heading || pseudo) {
      cur = { title: (heading ? heading[1] : pseudo[1]).replace(/:$/, '').trim(), lines: [] }
      sections.push(cur)
    } else if (cur) {
      cur.lines.push(raw)
    } else {
      preamble.push(raw)
    }
  }

  // Normalize bullets inside each section; drop "Full Changelog" lines
  // (the compare URL is already rendered in the release header).
  for (const s of sections) {
    s.lines = s.lines
      .filter((l) => !/^\s*\*\*Full Changelog\*\*/.test(l))
      .map((l) => (/^[*-]\s+|^\s+[*-]\s+/.test(l) ? normalizeBullet(l) : l))
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .split('\n')
  }

  return { preamble: preamble.join('\n').trim(), sections }
}

/** Extract the "Full Changelog" compare URL from a raw release body. */
function compareUrl(body, fallback) {
  const m = (body || '').match(
    /https?:\/\/github\.com\/terminusdb\/terminusdb\/compare\/[^\s)]*/,
  )
  return m ? m[0] : fallback
}

function normalizeRelease(raw) {
  const m = raw.tag_name.match(/^v?(\d+\.\d+\.\d+(?:-\d+)?)/)
  if (!m) return null
  const version = m[1]
  const date = (raw.published_at || raw.created_at || '').slice(0, 10)
  const { preamble, sections } = parseBody(raw.body)
  return {
    tag: raw.tag_name,
    version,
    date,
    line: lineFor(version),
    slug: slugFor(version),
    url: raw.html_url,
    compare: compareUrl(raw.body, null),
    preamble,
    sections,
    hasFeatures: sections.some((s) => FEATURE_SECTION.test(s.title)),
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// Feature pages on disk
// ─────────────────────────────────────────────────────────────────────────────

function readFrontmatter(file) {
  const content = fs.readFileSync(file, 'utf-8')
  const m = content.match(/^---\n([\s\S]*?)\n---/)
  if (!m) return null
  try {
    return yaml.load(m[1])
  } catch {
    return null
  }
}

/** Map release.version → { file, slug, draft, title } for pages under releases/. */
function featurePagesOnDisk() {
  const pages = new Map()
  if (!fs.existsSync(RELEASES_DIR)) return pages
  for (const entry of fs.readdirSync(RELEASES_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const file = path.join(RELEASES_DIR, entry.name, 'page.md')
    if (!fs.existsSync(file)) continue
    const fm = readFrontmatter(file) || {}
    const version = fm.release && fm.release.version
    if (!version) continue
    const draft = fm.draft === true || fm.status === 'draft'
    pages.set(String(version), {
      file,
      slug: entry.name,
      draft,
      title: fm.title || '',
    })
  }
  return pages
}

/** "UUID v7 Keys and …" from "TerminusDB 12.0.8: …" or "… | TerminusDB 12.0.8". */
function shortTitle(fullTitle, version) {
  let t = fullTitle
  const prefix = `TerminusDB ${version}:`
  if (t.startsWith(prefix)) t = t.slice(prefix.length).trim()
  t = t.replace(/\s*\|\s*TerminusDB\s+[\d.]+\s*$/, '').trim()
  return t
}

// ─────────────────────────────────────────────────────────────────────────────
// Rendering
// ─────────────────────────────────────────────────────────────────────────────

function fm(obj) {
  return `---\n${yaml.dump(obj, { lineWidth: -1, noRefs: true })}---\n`
}

function formatDate(iso) {
  const [y, m, d] = iso.split('-').map(Number)
  const months = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December',
  ]
  return `${d} ${months[m - 1]} ${y}`
}

function renderIndex(lines, pages) {
  const out = []
  for (const { title, slug, releases } of lines) {
    out.push(`## [${title}](/docs/releases/${slug}/)\n`)
    for (const r of releases) {
      const page = pages.get(r.version)
      const head =
        `- {% gh href="${r.url}" /%} {% tnum %}${r.date}{% /tnum %} ` +
        `([v${r.version}](${r.url})):`
      if (page && !page.draft) {
        out.push(`${head} [${shortTitle(page.title, r.version)}](/docs/releases/${page.slug}/)`)
      } else if (page && !/TODO/.test(page.title)) {
        // Authored draft stub: title as plain text — drafts aren't public.
        out.push(`${head} ${shortTitle(page.title, r.version)}`)
      } else {
        out.push(`${head} Minor bug fixes and maintenance`)
      }
    }
    out.push('')
  }

  return (
    fm({
      tags: ['release-notes', 'reference'],
      ai: 'generated',
      title: 'TerminusDB Release Notes',
      nextjs: {
        metadata: {
          title: 'TerminusDB Release Notes & Changelogs',
          description:
            'Release notes for every open-source TerminusDB release, newest first. Feature pages for major changes, plus a full changelog per minor line.',
          keywords:
            'terminusdb release notes, terminusdb changelog, terminusdb releases, terminusdb new features',
          alternates: { canonical: `${SITE}/docs/releases/` },
        },
      },
    }) +
    `\n${MARKER}\n\n` +
    'Release notes for every open-source TerminusDB release, newest first. ' +
    'Releases with a feature page are linked to a short write-up of what shipped; ' +
    'each minor line also has a full changelog.\n\n' +
    out.join('\n')
  )
}

function renderChangelog(line, releases, pages) {
  const out = []

  for (const r of releases) {
    out.push(`## v${r.version} {% #${anchorFor(r.version)} %}\n`)
    const bits = [`Released ${formatDate(r.date)}`, `[GitHub release](${r.url})`]
    const page = pages.get(r.version)
    if (page && !page.draft) {
      bits.push(`[Feature page](/docs/releases/${page.slug}/)`)
    }
    if (r.compare) bits.push(`[Full changelog](${r.compare})`)
    out.push(bits.join(' · ') + '\n')

    if (r.preamble) out.push(r.preamble + '\n')

    if (r.sections.length === 0) {
      // No section headings in the notes — nothing more to render.
    } else {
      for (const s of r.sections) {
        if (/^full changelog$/i.test(s.title)) continue
        out.push(`### ${s.title}\n`)
        const body = s.lines.join('\n').trim()
        if (body) out.push(body + '\n')
      }
    }
    out.push('')
  }

  return (
    fm({
      tags: ['release-notes', 'reference'],
      ai: 'generated',
      title: `${line.title} Changelog`,
      nextjs: {
        metadata: {
          title: `${line.title} Changelog — Release Notes`,
          description: changelogDescription(line),
          keywords: `terminusdb ${line.id} changelog, terminusdb ${line.id} release notes, terminusdb releases`,
          alternates: {
            canonical: `${SITE}/docs/releases/${line.slug}/`,
          },
        },
      },
    }) +
    `\n${MARKER}\n\n` +
    `Every open-source release in the ${line.title} line, newest first. ` +
    `Releases marked with a feature page link have a dedicated write-up of what shipped.\n\n` +
    out.join('\n')
  )
}

function changelogDescription(line) {
  // 140–160 chars
  const base = `All ${line.title} open-source releases in one place: release notes, bug fixes and new features for every version, newest first, with links to feature pages.`
  return base.length > 160 ? base.slice(0, 157) + '…' : base
}

function renderStub(release, prevNext, pages) {
  const featureBullets = release.sections
    .filter((s) => FEATURE_SECTION.test(s.title))
    .flatMap((s) => s.lines.filter((l) => l.trim()))
    .join('\n')

  const fixes = release.sections
    .filter(
      (s) =>
        !FEATURE_SECTION.test(s.title) &&
        !/^(full changelog|new contributors)/i.test(s.title),
    )
    .flatMap((s) => s.lines.filter((l) => l.trim()))
    .join('\n')

  const compare =
    release.compare ||
    `https://github.com/${GH_REPO}/releases/tag/${release.tag}`

  const body = []
  body.push(
    'TODO(human): write a 1-sentence intro naming the headline capability of this release, ' +
      'then a 3-bullet summary. Model: [TerminusDB 12.0.8](/docs/releases/12-0-8-uuid-v7-faster-json-loading/).\n',
  )
  body.push('## What shipped\n')
  body.push(featureBullets || '- (see GitHub release notes)')
  body.push('')
  body.push(
    'TODO(human): for each feature above add *What it does* / *Why it matters* / *Example* / *Read more* sections.\n',
  )
  if (fixes) {
    body.push('## Fixes\n')
    body.push(fixes)
    body.push('')
  }
  body.push('## Upgrade\n')
  body.push('```bash')
  body.push(`docker pull terminusdb/terminusdb-server:v${release.version}`)
  body.push('```\n')
  body.push(
    `[Docker install guide](/docs/install-terminusdb-as-a-docker-container/) · ` +
      `[Full changelog on GitHub](${compare})\n`,
  )
  body.push('---\n')
  body.push(prevNext)

  return (
    fm({
      tags: ['release-notes'],
      draft: true,
      status: 'draft',
      ai: 'assisted',
      title: `TODO(human): TerminusDB ${release.version} release title`,
      release: {
        version: release.version,
        date: release.date,
        line: release.line,
        edition: 'open-source',
        github: release.url,
      },
      nextjs: {
        metadata: {
          title: `TODO(human): TerminusDB ${release.version} title (<=60 chars)`,
          description:
            'TODO(human): write a 140–160 character description of what this release lets users do.',
          keywords: `terminusdb ${release.version}, terminusdb release notes`,
          robots: 'noindex, nofollow',
          alternates: {
            canonical: `${SITE}/docs/releases/${release.slug}/`,
          },
        },
      },
    }) +
    `\n${MARKER}\n\n` +
    body.join('\n')
  )
}

function prevNextLinks(release, featureReleases, pages, lineSlug) {
  const idx = featureReleases.findIndex((r) => r.version === release.version)
  const prev = featureReleases[idx + 1]
  const next = featureReleases[idx - 1]
  const links = []
  if (prev) {
    const p = pages.get(prev.version)
    const label =
      p && !p.draft ? shortTitle(p.title, prev.version) : `TerminusDB ${prev.version}`
    links.push(`**Previous:** [${label}](/docs/releases/${p?.slug ?? prev.slug}/)`)
  }
  if (next) {
    const n = pages.get(next.version)
    const label =
      n && !n.draft ? shortTitle(n.title, next.version) : `TerminusDB ${next.version}`
    links.push(`**Next:** [${label}](/docs/releases/${n?.slug ?? next.slug}/)`)
  }
  links.push(
    `[TerminusDB ${release.line} changelog](/docs/releases/${lineSlug}/)`,
    '[Release index](/docs/releases/)',
  )
  return links.join(' · ')
}

// ─────────────────────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  let raw
  try {
    raw = await fetchAllReleases()
  } catch (err) {
    if (fs.existsSync(DATA_FILE)) {
      console.warn(
        `GitHub fetch failed (${err.message}); using cached src/data/releases.json`,
      )
      raw = JSON.parse(fs.readFileSync(DATA_FILE, 'utf-8'))
    } else {
      throw err
    }
  }

  fs.mkdirSync(path.dirname(DATA_FILE), { recursive: true })
  fs.writeFileSync(DATA_FILE, JSON.stringify(raw, null, 2) + '\n')
  console.log(`Cached ${raw.length} releases to src/data/releases.json`)

  // Normalize: skip drafts and pre-releases.
  const releases = raw
    .filter((r) => !r.draft && !r.prerelease)
    .map(normalizeRelease)
    .filter(Boolean)
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0))

  const skipped = raw.length - releases.length
  if (skipped) console.log(`Skipped ${skipped} draft/pre-release entries`)

  // Group by line.
  const lines = LINES.map((l) => ({
    ...l,
    releases: releases.filter((r) => r.line === l.id),
  }))
  const ungrouped = releases.filter(
    (r) => !lines.some((l) => l.releases.includes(r)),
  )
  if (ungrouped.length) {
    console.warn(
      `WARNING: ${ungrouped.length} releases outside known lines: ` +
        ungrouped.map((r) => r.tag).join(', '),
    )
  }

  fs.mkdirSync(RELEASES_DIR, { recursive: true })

  // ── 1. Draft stubs for feature releases with no page yet ──────────────────
  // Pages are matched by frontmatter release.version — a directory may be
  // renamed freely (version + capability slug) without a stub reappearing.
  const existingPages = featurePagesOnDisk()
  let stubs = 0
  for (const line of lines) {
    const featureReleases = line.releases.filter((r) => r.hasFeatures)
    for (const r of featureReleases) {
      if (existingPages.has(r.version)) continue

      const prevNext = prevNextLinks(r, featureReleases, existingPages, line.slug)
      const pageFile = path.join(RELEASES_DIR, r.slug, 'page.md')
      fs.mkdirSync(path.dirname(pageFile), { recursive: true })
      fs.writeFileSync(pageFile, renderStub(r, prevNext, existingPages))
      stubs++
    }
  }
  console.log(`Created ${stubs} draft stub page(s)`)

  // ── 2. Generated index + per-line changelogs (always overwritten) ─────────
  const pages = featurePagesOnDisk()

  fs.writeFileSync(path.join(RELEASES_DIR, 'page.md'), renderIndex(lines, pages))

  for (const line of lines) {
    const dir = path.join(RELEASES_DIR, line.slug)
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(
      path.join(dir, 'page.md'),
      renderChangelog(line, line.releases, pages),
    )
    console.log(`Wrote ${line.slug} changelog (${line.releases.length} releases)`)
  }

  console.log('Done.')
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
